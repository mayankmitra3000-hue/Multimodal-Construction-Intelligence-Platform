from __future__ import annotations

import json
import logging
import time
from dataclasses import dataclass
from datetime import datetime, timezone
from typing import Any, Callable, Protocol, TypeVar

from pydantic import BaseModel

from ..config import Settings
from ..schemas.common import ResponseMeta

logger = logging.getLogger(__name__)

T = TypeVar("T", bound=BaseModel)
MockBuilder = Callable[[], dict[str, Any]]


class AIProviderError(RuntimeError):
    """Raised when the configured AI provider cannot produce a valid answer."""


@dataclass(frozen=True)
class ImageInput:
    data: bytes
    mime_type: str
    filename: str | None = None


class AIProvider(Protocol):
    model: str

    async def generate_json(
        self,
        *,
        system_prompt: str,
        user_prompt: str,
        image: ImageInput | None,
    ) -> str: ...


@dataclass
class AIResult:
    data: BaseModel
    meta: ResponseMeta


MOCK_WARNING = (
    "Demo mode: this response was generated by the deterministic mock engine. "
    "Set GEMINI_API_KEY to use live multimodal analysis."
)


def _schema_without_meta(schema: type[BaseModel]) -> dict[str, Any]:
    contract = schema.model_json_schema()
    properties = contract.get("properties", {})
    properties.pop("meta", None)
    required = contract.get("required")
    if required:
        contract["required"] = [name for name in required if name != "meta"]
    return contract


def build_system_prompt(feature_prompt: str, schema: type[BaseModel]) -> str:
    contract = json.dumps(_schema_without_meta(schema), separators=(",", ":"))
    return (
        "You are a senior construction intelligence analyst. You combine site-safety "
        "knowledge, structural engineering awareness, quantity surveying, and project "
        "controls. Be precise, conservative, and actionable. If evidence is missing or "
        "ambiguous, say so and lower confidence rather than inventing facts. You are a "
        "decision-support tool, not a substitute for a licensed professional.\n\n"
        f"{feature_prompt}\n\n"
        "OUTPUT CONTRACT:\n"
        "- Return ONLY one valid JSON object. No markdown fences, no prose before or after.\n"
        "- Do not include a 'meta' field; the server adds telemetry.\n"
        "- Populate every required field with the specified type.\n"
        "- Use ISO dates (YYYY-MM-DD) and uppercase 3-letter currency codes.\n"
        f"- The response must validate against this JSON Schema: {contract}"
    )


def _strip_code_fences(text: str) -> str:
    cleaned = text.strip()
    if cleaned.startswith("```"):
        lines = cleaned.splitlines()
        if lines and lines[0].startswith("```"):
            lines = lines[1:]
        if lines and lines[-1].strip() == "```":
            lines = lines[:-1]
        cleaned = "\n".join(lines).strip()
    return cleaned


class AIService:
    def __init__(self, settings: Settings, provider: AIProvider | None = None):
        self.settings = settings
        self.mode = settings.effective_mode
        self.provider = provider
        if self.mode == "gemini" and self.provider is None and settings.provider_configured:
            from .gemini import GeminiProvider

            self.provider = GeminiProvider(
                api_key=settings.gemini_api_key or "",
                model=settings.gemini_model,
            )

    @property
    def model_name(self) -> str:
        return self.provider.model if self.provider is not None else "deterministic-mock"

    async def analyze(
        self,
        *,
        schema: type[T],
        system_prompt: str,
        user_prompt: str,
        mock_builder: MockBuilder,
        image: ImageInput | None = None,
    ) -> AIResult:
        started = time.perf_counter()
        warnings: list[str] = []

        if self.provider is not None:
            error: Exception | None = None
            attempt_prompt = user_prompt
            for attempt in range(1, 3):
                try:
                    raw = await self.provider.generate_json(
                        system_prompt=system_prompt,
                        user_prompt=attempt_prompt,
                        image=image,
                    )
                    payload = self._decode(raw)
                    data = self._validate(schema, payload, started, warnings)
                    return AIResult(data=data, meta=data.meta)  # type: ignore[attr-defined]
                except Exception as exc:  # noqa: BLE001 - provider/parse failures
                    error = exc
                    logger.warning(
                        "Gemini attempt %s failed for %s: %s",
                        attempt,
                        schema.__name__,
                        exc,
                    )
                    attempt_prompt = (
                        f"{user_prompt}\n\nYour previous response was rejected: "
                        f"{exc}. Return corrected JSON that satisfies the contract."
                    )
            if self.settings.ai_mode == "gemini":
                raise AIProviderError(
                    f"Gemini could not produce a valid {schema.__name__} payload: {error}"
                ) from error
            warnings.append(
                f"Live AI response failed validation; served demo fallback ({error})."
            )
        elif self.settings.ai_mode == "gemini":
            raise AIProviderError(
                "AI_MODE=gemini but GEMINI_API_KEY is not configured. "
                "Add the key to backend/.env or switch AI_MODE=mock."
            )

        payload = mock_builder()
        latency = int((time.perf_counter() - started) * 1000)
        meta = ResponseMeta(
            source="mock",
            model="deterministic-mock",
            generated_at=datetime.now(timezone.utc),
            latency_ms=latency,
            warnings=[MOCK_WARNING, *warnings],
        )
        data = schema.model_validate({**payload, "meta": meta.model_dump()})
        return AIResult(data=data, meta=meta)

    @staticmethod
    def _decode(raw: str) -> dict[str, Any]:
        cleaned = _strip_code_fences(raw)
        payload = json.loads(cleaned)
        if not isinstance(payload, dict):
            raise ValueError("Model response must be a JSON object.")
        payload.pop("meta", None)
        return payload

    def _validate(
        self,
        schema: type[T],
        payload: dict[str, Any],
        started: float,
        warnings: list[str],
    ) -> T:
        latency = int((time.perf_counter() - started) * 1000)
        meta = ResponseMeta(
            source="gemini",
            model=self.model_name,
            generated_at=datetime.now(timezone.utc),
            latency_ms=latency,
            warnings=warnings,
        )
        return schema.model_validate({**payload, "meta": meta.model_dump()})
